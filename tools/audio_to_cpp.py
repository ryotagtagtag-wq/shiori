#!/usr/bin/env python3
"""バイナリファイル (音声等) を C++ の const uint8_t 配列 (PROGMEM 相当) に変換するスクリプト。

Usage:
    python3 tools/audio_to_cpp.py <input.wav|mp3|ogg> [output.hpp] [array_name]

出力:
    const uint32_t <array_name>_size;
    const uint8_t  <array_name>[] = { ... };
"""

import sys
from pathlib import Path


def sanitize_identifier(name: str) -> str:
    """ファイル名から C++ 識別子として安全な名前を生成する。"""
    ident = "".join(c if c.isalnum() or c == "_" else "_" for c in name)
    if ident and ident[0].isdigit():
        ident = "_" + ident
    return ident or "audio"


def convert_binary_to_cpp(input_path: Path, output_path: Path, array_name: str | None = None) -> None:
    data = input_path.read_bytes()
    size = len(data)

    if array_name is None:
        array_name = sanitize_identifier(input_path.stem)

    lines: list[str] = []
    lines.append(f"// Auto-generated by tools/audio_to_cpp.py from {input_path.name}")
    lines.append(f"// License: CC0 (see source asset page)")
    lines.append("")
    lines.append(f"const uint32_t {array_name}_size = {size};")
    lines.append(f"const uint8_t {array_name}[] = {{")

    for i in range(0, size, 16):
        chunk = data[i : i + 16]
        vals = ", ".join(str(b) for b in chunk)
        lines.append(f"    {vals},")

    lines.append("};")
    lines.append("")

    output_path.write_text("\n".join(lines), encoding="utf-8")


def main() -> None:
    if len(sys.argv) < 2:
        print("Usage: python3 audio_to_cpp.py <input.wav|mp3|ogg> [output.hpp] [array_name]")
        sys.exit(1)

    input_path = Path(sys.argv[1])
    if not input_path.exists():
        print(f"Input file not found: {input_path}")
        sys.exit(1)

    if len(sys.argv) >= 3:
        output_path = Path(sys.argv[2])
    else:
        output_path = input_path.with_suffix(".hpp")

    array_name = sys.argv[3] if len(sys.argv) >= 4 else None

    convert_binary_to_cpp(input_path, output_path, array_name)
    print(f"Generated: {output_path} (array: {array_name or sanitize_identifier(input_path.stem)}, size: {len(input_path.read_bytes())} bytes)")


if __name__ == "__main__":
    main()
