#!/usr/bin/env python3
"""画像 (PNG) を C++ の const uint8_t 配列 (PROGMEM 相当) に変換するスクリプト。

Usage:
    python3 tools/asset_to_cpp.py <input.png> [output.hpp] [array_name]

出力:
    const uint16_t <array_name>_width;
    const uint16_t <array_name>_height;
    const uint8_t  <array_name>[] = { R, G, B, A, ... };
"""

import sys
from pathlib import Path

from PIL import Image


def sanitize_identifier(name: str) -> str:
    """ファイル名から C++ 識別子として安全な名前を生成する。"""
    ident = "".join(c if c.isalnum() or c == "_" else "_" for c in name)
    if ident and ident[0].isdigit():
        ident = "_" + ident
    return ident or "image"


def convert_png_to_cpp(input_path: Path, output_path: Path, array_name: str | None = None) -> None:
    img = Image.open(input_path).convert("RGBA")
    width, height = img.size
    pixels = list(img.tobytes())
    if array_name is None:
        array_name = sanitize_identifier(input_path.stem)

    lines: list[str] = []
    lines.append(f"// Auto-generated by tools/asset_to_cpp.py from {input_path.name}")
    lines.append(f"// License: CC0 (see source asset page)")
    lines.append("")
    lines.append(f"const uint16_t {array_name}_width = {width};")
    lines.append(f"const uint16_t {array_name}_height = {height};")
    lines.append(f"const uint8_t {array_name}[] = {{")

    for i in range(0, len(pixels), 16):
        chunk = pixels[i : i + 16]
        vals = ", ".join(str(v) for v in chunk)
        lines.append(f"    {vals},")

    lines.append("};")
    lines.append("")

    output_path.write_text("\n".join(lines), encoding="utf-8")


def main() -> None:
    if len(sys.argv) < 2:
        print("Usage: python3 asset_to_cpp.py <input.png> [output.hpp] [array_name]")
        sys.exit(1)

    input_path = Path(sys.argv[1])
    if not input_path.exists():
        print(f"Input file not found: {input_path}")
        sys.exit(1)

    if len(sys.argv) >= 3:
        output_path = Path(sys.argv[2])
    else:
        output_path = input_path.with_suffix(".hpp")

    array_name = sys.argv[3] if len(sys.argv) >= 4 else None

    convert_png_to_cpp(input_path, output_path, array_name)
    print(f"Generated: {output_path} (array: {array_name or sanitize_identifier(input_path.stem)})")


if __name__ == "__main__":
    main()
